def q(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "''") + "'"


def main():
    rnd = random.Random(42)
    out = ["-- GENERATED by db/seed/gen_seed.py. DEV/DEMO DATA ONLY. Do not edit by hand.", "SET NAMES utf8mb4;", ""]

