#!/usr/bin/env python3
"""Generates db/seed/002_demo_history.sql: ~140 historical orders over the last 45 days, extra
customers, payments and audit trail, so the admin dashboard has real data to show.

DEV/DEMO DATA ONLY. Deterministic (fixed RNG seed); timestamps are RELATIVE to load time
(NOW() - INTERVAL ...), so the charts always look current.

Every row is consistent with the engine's rules, so `reconcile` passes on the result:
  * the net effect on inventory.on_hand is zero (a historical restock exactly covers what was sold),
    so the base seed's stock levels are unchanged;
  * ledger deltas, reservation states and payment attempts follow the same transitions as src/orders.c;
  * only 2 very recent orders are still PENDING_PAYMENT (they hold stock via `reserved`).
The "last one" keyboard (SF-KB-FOUNDER) is deliberately never sold here.

Regenerate:  python3 db/seed/gen_history.py db/seed/002_demo_history.sql
"""
import os
import random
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from gen_seed import CATS, CUST_HASH, q  # noqa: E402

B32 = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
NAMES = ["Maya Chen", "Tomás Rivera", "Priya Nair", "Jonas Weber", "Amara Okafor", "Liam O'Brien", "Sofia Rossi",
         "Kenji Watanabe", "Hannah Berg", "Diego Alvarez", "Noor Hassan", "Elena Petrova"]
rnd = random.Random(7)


def public_id():
    return "".join(rnd.choice(B32) for _ in range(26))


def load_products():
    here = os.path.dirname(__file__)
    seed = open(os.path.join(here, "001_seed.sql"), encoding="utf-8").read()
    stock = {int(a): int(b) for a, b in re.findall(r"^\((\d+), (\d+), 0, \d+\)", seed, re.M)}
    rows, pid = [], 0
    for cid, (slug, cname, code, _tag, items) in enumerate(CATS, 1):
        for n, (name, price) in enumerate(items, 1):
            pid += 1
            sku = "SF-KB-FOUNDER" if name.startswith("Founder's Edition") else f"SF-{code}-{n:03d}"
            rows.append(dict(id=pid, sku=sku, name=name, price=price, stock=stock[pid], founder=sku == "SF-KB-FOUNDER"))
    assert len(rows) == 48 and len(stock) == 48, "001_seed.sql no longer matches gen_seed.CATS"
    return rows


def pick_status(age_h):
    r = rnd.random()
    if age_h < 0.2: return "PENDING_PAYMENT" if r < 0.5 else "PAID"
    if age_h < 30: return "PAID" if r < .45 else "SHIPPED" if r < .8 else "CANCELLED" if r < .9 else "EXPIRED"
    if age_h < 100: return "SHIPPED" if r < .35 else "DELIVERED" if r < .75 else "PAID" if r < .82 else "CANCELLED" if r < .93 else "EXPIRED"
    return "DELIVERED" if r < .84 else "CANCELLED" if r < .94 else "EXPIRED"


def main():
    products = [p for p in load_products() if not p["founder"]]
    sellable = [p for p in products if p["stock"] > 0] + [p for p in products if p["stock"] == 0]
    out = ["-- GENERATED by db/seed/gen_history.py. DEV/DEMO DATA ONLY. Do not edit by hand.", "SET NAMES utf8mb4;", ""]

    # ---- customers (ids 4..15); ava (2) and ben (3) come from the base seed and also get orders
    users = []
    for i, name in enumerate(NAMES):
        uid = 4 + i
        local = name.lower().replace("'", "").replace("á", "a").replace("ó", "o").replace(" ", ".")
        users.append(uid)
        out.append(f"INSERT INTO users (id, email, password_hash, display_name, role, created_at) VALUES "
                   f"({uid}, {q(local + '@example.test')}, {q(CUST_HASH)}, {q(name)}, 'customer', NOW(3) - INTERVAL {rnd.randint(2000, 60000)} MINUTE);")
    buyers = [2, 3] + users

    orders, items, resv, ledger, audit, pays = [], [], [], [], [], []
    sold_total = {}                                   # pid -> units that left on_hand and never came back
    n_orders = 140
    # more orders on recent days and on weekdays, so the revenue chart has a believable shape
    days = list(range(45))
    weights = [(0.55 + 0.45 * (45 - d) / 45) * (0.6 if d % 7 in (1, 2) else 1.0) for d in days]
    stamps = []
    for _ in range(n_orders):
        d = rnd.choices(days, weights)[0]
        stamps.append(d * 1440 + rnd.randint(30, 1400) if d else rnd.randint(2, 900))
    stamps.sort(reverse=True)                         # oldest first => ids ascend with time
    stamps[-2], stamps[-1] = 3, 1                     # two orders created moments ago (still oldest-first)

    for oid, minutes_ago in enumerate(stamps, 1):
        age_h = minutes_ago / 60
        status = pick_status(age_h)
        if minutes_ago > 4:
            while status == "PENDING_PAYMENT":
                status = pick_status(age_h)
        uid = rnd.choice(buyers)
        lines = []
        for p in rnd.sample(sellable, rnd.choice([1, 1, 2, 2, 3])):
            lines.append((p, rnd.choice([1, 1, 1, 2])))
        if status == "PENDING_PAYMENT":              # a held reservation needs real stock behind it
            lines = [(p, q_) for p, q_ in lines if p["stock"] >= 5] or [(next(p for p in products if p["stock"] >= 12), 1)]
        pub = public_id()
        total = sum(p["price"] * qty for p, qty in lines)
        t0 = minutes_ago
        paid_at = max(0, t0 - rnd.randint(1, 6))
        ship_at = paid_at - rnd.randint(300, 1500)
        deliv_at = ship_at - rnd.randint(1500, 5000)
        is_paid = status in ("PAID", "SHIPPED", "DELIVERED")
        cancelled_after_paid = status == "CANCELLED" and age_h > 1 and rnd.random() < 0.5
        end_at = {"PAID": paid_at, "SHIPPED": ship_at, "DELIVERED": deliv_at}.get(status, max(0, t0 - rnd.randint(5, 40) if status == "CANCELLED" else t0 - 15))
        end_at = max(end_at, 0)
        version = {"PENDING_PAYMENT": 1, "PAID": 2, "SHIPPED": 3, "DELIVERED": 4}.get(status, 3 if cancelled_after_paid else 2)
        expires = f"NOW(3) - INTERVAL {t0} MINUTE + INTERVAL 15 MINUTE" if status == "PENDING_PAYMENT" else "NULL"
        orders.append(f"({oid}, '{pub}', {uid}, '{status}', {total}, 'USD', {version}, {expires}, NOW(3) - INTERVAL {t0} MINUTE, NOW(3) - INTERVAL {end_at} MINUTE)")

        def aud(action, actor, at, det=None):
            audit.append(f"({actor if actor else 'NULL'}, '{action}', 'order', '{pub}', {q(det) if det else 'NULL'}, NOW(3) - INTERVAL {max(at, 0)} MINUTE)")

        aud("order.created", uid, t0, f'{{"total_cents": {total}, "lines": {len(lines)}}}')
        for p, qty in lines:
            items.append(f"({oid}, {p['id']}, {q(p['sku'])}, {q(p['name'])}, {p['price']}, {qty})")
            rstat = {"PENDING_PAYMENT": "held", "PAID": "committed", "SHIPPED": "committed", "DELIVERED": "committed"}.get(status, "released")
            resv.append(f"({oid}, {p['id']}, {qty}, '{rstat}', NOW(3) - INTERVAL {t0} MINUTE, NOW(3) - INTERVAL {end_at} MINUTE)")
            ledger.append(f"({p['id']}, 0, {qty}, 'reserve', {oid}, NOW(3) - INTERVAL {t0} MINUTE)")
            if status == "PENDING_PAYMENT":
                continue
            if is_paid or cancelled_after_paid:       # money taken: stock left on_hand
                ledger.append(f"({p['id']}, {-qty}, {-qty}, 'commit', {oid}, NOW(3) - INTERVAL {paid_at} MINUTE)")
                if cancelled_after_paid:
                    ledger.append(f"({p['id']}, {qty}, 0, 'restock', {oid}, NOW(3) - INTERVAL {end_at} MINUTE)")   # net zero
                else:
                    sold_total[p["id"]] = sold_total.get(p["id"], 0) + qty
            else:                                      # cancelled/expired unpaid: reservation released
                ledger.append(f"({p['id']}, 0, {-qty}, 'release', {oid}, NOW(3) - INTERVAL {end_at} MINUTE)")
        attempts = []
        if is_paid or cancelled_after_paid:
            if rnd.random() < 0.12:
                attempts.append(("decline", "failed", paid_at + 2))
            attempts.append(("success", "succeeded", paid_at))
        elif status in ("CANCELLED", "EXPIRED") and rnd.random() < 0.15:
            attempts.append(("decline", "failed", t0 - 2))
        for k, (scen, st, at) in enumerate(attempts, 1):
            pays.append(f"({oid}, {k}, '{scen}', '{st}', {total}, '{public_id()}', NOW(3) - INTERVAL {max(at, 0)} MINUTE)")
        if is_paid or cancelled_after_paid:
            aud("order.paid", uid, paid_at, f'{{"attempt": {len(attempts)}, "scenario": "success"}}')
        if status in ("SHIPPED", "DELIVERED"):
            aud("order.shipped", 1, ship_at, '{"from": "PAID", "to": "SHIPPED"}')
        if status == "DELIVERED":
            aud("order.delivered", 1, deliv_at, '{"from": "SHIPPED", "to": "DELIVERED"}')
        if status == "CANCELLED":
            aud("order.cancelled", uid if rnd.random() < .7 else 1, end_at, f'{{"from": "{"PAID" if cancelled_after_paid else "PENDING_PAYMENT"}"}}')
        if status == "EXPIRED":
            aud("order.expired", None, end_at)

    # Historical restocks: what was sold must have been on the shelf first, and the base seed's
    # on_hand already reflects the END state, so the restock is booked as ledger history only
    # together with the commits (net zero on the on_hand column).
    # (paid-then-cancelled orders already net to zero through their own commit + restock rows)
    for pid, units in sorted(sold_total.items()):
        ledger.append(f"({pid}, {units}, 0, 'restock', NULL, NOW(3) - INTERVAL 70000 MINUTE)")

    def block(table, cols, rows):
        for i in range(0, len(rows), 200):
            out.append(f"INSERT INTO {table} ({cols}) VALUES\n" + ",\n".join(rows[i:i + 200]) + ";")

    out.append("")
    block("orders", "id, public_id, user_id, status, total_cents, currency, version, expires_at, created_at, updated_at", orders)
    block("order_items", "order_id, product_id, sku, product_name, unit_price_cents, quantity", items)
    block("stock_reservations", "order_id, product_id, quantity, status, created_at, updated_at", resv)
    block("payment_attempts", "order_id, attempt_no, scenario, status, amount_cents, provider_ref, created_at", pays)
    block("inventory_ledger", "product_id, delta_on_hand, delta_reserved, reason, order_id, created_at", ledger)
    block("audit_events", "actor_user_id, action, entity_type, entity_id, details, created_at", audit)
    held = {}
    for r in resv:
        m = re.match(r"\((\d+), (\d+), (\d+), 'held'", r)
        if m:
            held[int(m.group(2))] = held.get(int(m.group(2)), 0) + int(m.group(3))
    for pid, n in sorted(held.items()):
        out.append(f"UPDATE inventory SET reserved = reserved + {n} WHERE product_id = {pid};")
    text = "\n".join(out) + "\n"
    if len(sys.argv) > 1:
        with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
